/**
 * HALT from two sources (ADR 0015): the `halted` label on the pinned loop
 * issue, which the owner clears from the tracker, and the local HALT file, a
 * per-machine kill switch. Pure: facts in, decision out. The status body is a
 * view generated from state and never read back.
 */

import type {AutomationState} from './state';

export const HALT_LABEL = 'halted';
export const LOOP_ISSUE_TITLE = 'Forger loop';

export interface HaltFacts {
  /** The pinned issue carries the halted label. */
  label: boolean;
  /** The reason the label was set with, when known. */
  labelReason: string | null;
  /** Contents of the local HALT file; null when there is none. */
  file: string | null;
}

export type HaltDecision =
  | {halted: false}
  | {halted: true; source: 'label' | 'file' | 'both'; reason: string};

export function decideHalt(facts: HaltFacts): HaltDecision {
  const labelReason = facts.labelReason?.trim() || 'halted by the halted label';
  const fileReason = facts.file === null ? null : facts.file.trim() || 'HALT file';
  if (facts.label && fileReason !== null) return {halted: true, source: 'both', reason: labelReason};
  if (facts.label) return {halted: true, source: 'label', reason: labelReason};
  if (fileReason !== null) return {halted: true, source: 'file', reason: fileReason};
  return {halted: false};
}

/** The one-screen status written to the pinned issue's body. */
export function statusBody(state: AutomationState, halted: boolean, now: Date): string {
  const running = state.in_flight.map(r => r.ticket ?? 'no ticket').join(', ');
  const rows = [
    `- Loop: ${halted ? 'halted' : 'running'}`,
    `- Status: ${state.status}`,
    `- Iteration: ${state.iteration}`,
    `- In flight: ${running === '' ? 'none' : running}`,
    `- Last completed: ${state.last_completed_at ?? 'never'}`,
  ];
  if (state.last_error) rows.push(`- Last error: ${state.last_error}`);
  return [
    '<!-- generated by forger; edits are overwritten and never read back -->',
    '',
    ...rows,
    '',
    halted
      ? `Remove the \`${HALT_LABEL}\` label to resume.`
      : `Add the \`${HALT_LABEL}\` label, with a comment saying why, to stop the loop.`,
    '',
    `Updated ${now.toISOString()}`,
    '',
  ].join('\n');
}
