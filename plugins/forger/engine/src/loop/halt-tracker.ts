/**
 * The `halted` label on the pinned loop issue, through the command port. A
 * failed read counts as "not set": a tracker outage must not stop a loop the
 * owner never halted. Reads are cached briefly because the runner polls.
 */

import type {CommandRunner} from '../ports';
import {HALT_LABEL, LOOP_ISSUE_TITLE} from './halt-label';

export const HALT_READ_TTL_MS = 30_000;

export interface TrackerHalt {
  /** The label state and the reason it was set with. */
  read(): {label: boolean; reason: string | null};
  set(reason: string): void;
  clear(): void;
  writeStatus(body: string): void;
}

function q(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

export class GhTrackerHalt implements TrackerHalt {
  private issue: number | null = null;
  private cached: {at: number; value: {label: boolean; reason: string | null}} | null = null;

  constructor(
    private run: CommandRunner,
    private now: () => number = Date.now,
    private title: string = LOOP_ISSUE_TITLE
  ) {}

  private find(): number | null {
    if (this.issue !== null) return this.issue;
    const out = this.run(
      `gh issue list --state open --search ${q(`"${this.title}" in:title`)} --json number,title --jq ${q(
        `[.[] | select(.title == "${this.title}")] | sort_by(.number) | .[0].number // empty`
      )}`
    ).trim();
    const n = Number(out);
    this.issue = out !== '' && Number.isInteger(n) ? n : null;
    return this.issue;
  }

  private ensure(): number {
    const found = this.find();
    if (found !== null) return found;
    const url = this.run(
      `gh issue create --title ${q(this.title)} --body ${q('Loop status, generated by forger.')}`
    ).trim();
    const n = Number(url.split('/').pop());
    if (!Number.isInteger(n)) throw new Error(`could not read the new loop issue from "${url}"`);
    try {
      this.run(`gh issue pin ${n}`);
    } catch {
      // Pinning needs a newer gh; the title still finds the issue.
    }
    this.issue = n;
    return n;
  }

  read(): {label: boolean; reason: string | null} {
    if (this.cached && this.now() - this.cached.at < HALT_READ_TTL_MS) return this.cached.value;
    let value: {label: boolean; reason: string | null} = {label: false, reason: null};
    try {
      const issue = this.find();
      if (issue !== null) {
        const labels = this.run(`gh issue view ${issue} --json labels --jq ".labels[].name"`)
          .split('\n')
          .map(l => l.trim().toLowerCase());
        if (labels.includes(HALT_LABEL)) {
          const reason = this.run(`gh issue view ${issue} --json comments --jq ".comments[-1].body // empty"`).trim();
          value = {label: true, reason: reason === '' ? null : reason};
        }
      }
    } catch {
      value = {label: false, reason: null};
    }
    this.cached = {at: this.now(), value};
    return value;
  }

  set(reason: string): void {
    const issue = this.ensure();
    this.run(`gh issue comment ${issue} --body ${q(reason)}`);
    this.run(`gh issue edit ${issue} --add-label ${HALT_LABEL}`);
    this.cached = {at: this.now(), value: {label: true, reason}};
  }

  clear(): void {
    const issue = this.find();
    if (issue !== null) this.run(`gh issue edit ${issue} --remove-label ${HALT_LABEL}`);
    this.cached = {at: this.now(), value: {label: false, reason: null}};
  }

  writeStatus(body: string): void {
    const issue = this.ensure();
    this.run(`gh issue edit ${issue} --body ${q(body)}`);
  }
}
